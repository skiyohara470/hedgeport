const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, ja }

/**
 * 指定言語の翻訳関数を作る純関数。
 * `{name}` 形式のプレースホルダを params で置換する。未知キーはキー文字列をそのまま返す。
 *
 * @param language 表示言語
 * @returns Translator
 */
export function createTranslator(language: Language): Translator {
  const dictionary = dictionaries[language] ?? en
  return (key, params) => {
    const template = dictionary[key] ?? en[key] ?? key
    if (!params) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
  }
}

/**
 * 表示メッセージの構造化表現。
 * renderer 生成は翻訳キー + パラメータ（言語切替で再翻訳可能）、main / server 由来は raw を保持する。
 */
export type Message = { key: TranslationKey; params?: TranslationParams } | { raw: string }

/** 構造化メッセージを現在の翻訳関数で文字列へ解決する。 */
export function resolveMessage(t: Translator, message: Message): string {
  return 'key' in message ? t(message.key, message.params) : message.raw
}
